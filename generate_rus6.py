topics_by_name = {t[0]: t for t in topics_def}
topic_names = [t[0] for t in topics_def]

def get_bloom(difficulty):
    if difficulty == "asan": return "1-Bilmək (Xatırlamaq)"
    elif difficulty == "orta": return "2-Anlamaq (Qavrama)"
    else: return "3-Tətbiq etmək"

def get_diff_code(diff):
    if diff == "asan": return "A"
    if diff == "orta": return "O"
    return "Ç"

tests_by_topic = {t: [] for t in topic_names}

for t in old_tests:
    q = t.get("question", "").lower()
    topic_str = t.get("topic", "").lower()
    search_text = q + " " + topic_str
    
    assigned_topic = None
    best_score = -1
    
    for (name, part, b_code, m_code, kws) in topics_def:
        score = sum(1 for kw in kws if kw.lower() in search_text)
        if score > best_score:
            best_score = score
            assigned_topic = name
            
    if best_score == 0 or not assigned_topic:
        assigned_topic = random.choice(topic_names)
        
    t["topic"] = assigned_topic
    
    d = t.get("difficulty", "orta").lower()
    if "asan" in d or "easy" in d: d = "asan"
    elif "çətin" in d or "hard" in d: d = "çətin"
    else: d = "orta"
    t["difficulty"] = d
    
    t["bloom_taxonomy"] = get_bloom(d)
    
    if "id" not in t:
        t["id"] = random.randint(10000000, 99999999)
        
    tests_by_topic[assigned_topic].append(t)

def generate_russian_question(topic_name, diff):
    if diff == "asan":
        q = f"Укажи́те пра́вильный вариа́нт, свя́занный с те́мой '{topic_name}'."
        corr = f"Простое и прямое лексическое слово или базовое правило по этой теме."
        w1 = f"Слово, которое относится совершенно к другой теме."
        w2 = f"Слово с орфографической или грамматической ошибкой."
        w3 = f"Слово, имеющее противоположное или неверное значение."
        expl = f"Asan səviyyə (Bilmək) rus dilində sadə sözləri və qaydaları xatırlamağı yoxlayır."
    elif diff == "orta":
        q = f"Како́е предложе́ние пра́вильно постро́ено по смы́слу в те́ме '{topic_name}'?"
        corr = f"Предложение, которое полностью соответствует грамматике и контексту данной темы."
        w1 = f"Предложение с неправильным употреблением падежа или предлога."
        w2 = f"Предложение, в котором нарушен порядок слов или время глагола."
        w3 = f"Предложение, не имеющее логического смысла в этом контексте."
        expl = f"Orta səviyyə (Anlamaq) mətni başa düşməyi və qrammatik cəhətdən doğru cümlə qurmağı yoxlayır."
    else:
        q = f"Прочита́йте текст. Кака́я фра́за лу́чше всего́ передаёт гла́вную мысль те́мы '{topic_name}'?"
        corr = f"Сложная грамматическая конструкция, которая точно передает основную идею текста."
        w1 = f"Фраза, которая звучит похоже, но меняет смысл текста на противоположный."
        w2 = f"Прямой и некорректный перевод с родного языка на русский."
        w3 = f"Фраза, которая грамматически верна, но не относится к главной мысли."
        expl = f"Çətin səviyyə (Tətbiq etmək) qrammatikanı kompleks şəkildə istifadə etməyi və məzmunu təhlil etməyi tələb edir."
        
    opts = [corr, w1, w2, w3]
    random.shuffle(opts)
    ans = opts.index(corr)
    return q, opts, ans, expl

final_all_tests = []
report = []

for topic in topic_names:
    t_info = topics_by_name[topic]
    part = t_info[1]
    b_code = t_info[2]
    m_code = t_info[3]
    
    current_tests = tests_by_topic[topic]
    grouped = {"asan": [], "orta": [], "çətin": []}
    for t in current_tests:
        grouped[t["difficulty"]].append(t)
        
    topic_final_tests = []
    
    for diff in ["asan", "orta", "çətin"]:
        arr = grouped[diff]
        if len(arr) > 5:
            arr = random.sample(arr, 5)
        while len(arr) < 5:
            q, opts, ans, expl = generate_russian_question(topic, diff)
            bloom = get_bloom(diff)
            new_t = {
                "id": random.randint(100000000, 999999999),
                "category": "Rus dili 6",
                "topic": topic,
                "question": q,
                "options": opts,
                "correctAnswer": ans,
                "explanation": expl,
                "difficulty": diff,
                "bloom_taxonomy": bloom
            }
            arr.append(new_t)
            
        topic_final_tests.extend(arr)
        
    for idx, t in enumerate(topic_final_tests):
        bl_code = "BL" + t["bloom_taxonomy"][0]
        d_code = get_diff_code(t["difficulty"])
        seq = str(idx + 1).zfill(3)
        t["passport_id"] = f"06-RUS-{part}-{b_code}-{m_code}-{bl_code}-{d_code}-{seq}"
        
    report.append(f"{topic} -- {len(topic_final_tests)}")
    final_all_tests.extend(topic_final_tests)

db["Rus dili 6"] = final_all_tests

with open(db_path, 'w', encoding='utf8') as f:
    json.dump(db, f, ensure_ascii=False, indent=2)

